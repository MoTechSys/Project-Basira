import json, urllib.request, sys
U="http://localhost:8011/v1/check"
def check(text, mode="text"):
    req=urllib.request.Request(U, data=json.dumps({"text":text,"ui_lang":"ar"}).encode(), headers={"Content-Type":"application/json"})
    try:
        r=json.load(urllib.request.urlopen(req, timeout=30))
    except urllib.error.HTTPError as e:
        return {"error":e.code, "body":e.read()[:200].decode(errors='ignore')}
    return r
