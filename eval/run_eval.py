def _our_strings(resp: dict[str, Any], pipeline: Pipeline) -> list[str]:
    out: list[str] = []
    for q in resp["quotes"]:
        for msgs in (pipeline.msgs_ar, pipeline.msgs_en):
            if msgs.has("status", q["message_key"]):
                out.append(msgs.get("status", q["message_key"]))
            for k in q["notice_keys"]:
                if k != "grade_line" and msgs.has("notice", k):
                    out.append(msgs.get("notice", k))
        for m in q["matches"]:
            out += [m["ref_label_ar"], m["ref_label_en"], *m["diff_kinds"]]
    return out


def _pick_quote(resp: dict[str, Any], quote: str) -> dict[str, Any] | None:
    """The quote result whose span covers the materialized quote (longest overlap)."""
    best, best_ov = None, 0
    text = resp["_text"]
    qs = text.find(quote)
    qe = qs + len(quote)
    for q in resp["quotes"]:
        a, b = q["span"]["start"], q["span"]["end"]
        ov = max(0, min(b, qe) - max(a, qs))
        if ov > best_ov:
            best, best_ov = q, ov
    return best or (resp["quotes"][0] if resp["quotes"] else None)


async def run_cases(
    pipeline: Pipeline, cases: list[dict[str, Any]], repeats: int
) -> tuple[list[CaseOutcome], list[dict[str, Any]], int]:
    outcomes: list[CaseOutcome] = []
    details: list[dict[str, Any]] = []
    variance = 0
    for case in cases:
        mat = materialize(pipeline.store, case)
        runs: list[dict[str, Any]] = []
        for _ in range(repeats):
            t0 = time.perf_counter()
            r = await pipeline.check(CheckRequest(text=mat.text))
            d = r.model_dump()
            d["_text"] = mat.text
            d["_latency"] = int((time.perf_counter() - t0) * 1000)
            runs.append(d)
        keyed = [
            json.dumps(
                {k: v for k, v in d.items() if k not in ("request_id", "timings_ms", "_latency")},
                sort_keys=True,
                ensure_ascii=False,
            )
            for d in runs
        ]
        if len(set(keyed)) > 1:
            variance += 1
        resp = runs[0]
        q = _pick_quote(resp, mat.quote)
        forb = sum(len(scan_forbidden(s)) for s in _our_strings(resp, pipeline))
        expect = {**mat.expect, "_id": mat.case_id, "_cat": mat.category}
        o = judge(expect, q, resp, forbidden_hits=forb)
        o.latency_ms = max(d["_latency"] for d in runs)
        outcomes.append(o)
        details.append(
            {
                "id": mat.case_id,
                "category": mat.category,
                "passed": o.passed,
                "unsafe": o.unsafe,
                "reasons": o.reasons,
                "got": o.got_status,
                "expected": o.expected_status,
                "notes": mat.notes,
                "n_quotes": len(resp["quotes"]),
            }
        )
    return outcomes, details, variance


def write_report(
    agg_all: Aggregate,
    per_cat: dict[str, Aggregate],
    details: list[dict[str, Any]],
    fa: dict[str, Any] | None,
    meta: dict[str, Any],
) -> None:
    s = agg_all.summary()
    lines = [
        "# eval/REPORT.md — evaluation report (generated by eval/run_eval.py)",
        "",
        f"**Index:** `{meta['index']}` (records sha256 `{meta['records_sha256'][:12]}…`) · **provider:** {meta['provider']} · **repeats:** {meta['repeats']} · **date:** {meta['date']}",
        "",
        "## Headline",
        "",
        "| metric | value | n | 95 % CI (Wilson) | note |",
        "|---|---|---|---|---|",
    ]

    def row(name: str, d: dict[str, Any], note: str = "") -> str:
        rate = "—" if d["rate"] is None else f"{d['rate']:.3f}"
        ci = (
            f"[{d['ci95'][0]:.3f}, {d['ci95'][1]:.3f}]"
            if "ci95" in d
            else ("indicative (n<30)" if d.get("indicative") else "—")
        )
        return f"| {name} | {rate} | {d['k']}/{d['n']} | {ci} | {note} |"

    lines += [
        row("pass rate (all cases)", s["pass"]),
        row("**unsafe verdicts** (forbidden status emitted)", s["unsafe"], "target 0"),
        row("recall@found", s["recall_found"], "expected `found` → got `found` with expected record"),
        row("precision@found", s["precision_found"], "got `found` → `found` was expected"),
        f"| forbidden-lexicon hits in our strings | {s['forbidden_hits']} | — | — | target 0 |",
        f"| latency per case (ms) | p50 {s['latency_ms']['p50']} · p95 {s['latency_ms']['p95']} · max {s['latency_ms']['max']} | — | — | in-process, incl. mock extraction |",
        f"| output variance across repeats | {meta['variance_cases']} cases differed | — | — | extraction variance only (core is deterministic) |",
    ]
    if fa:
        lines += [
            f"| **false-alarm rate** (verbatim segment not `found`) | {fa['rate']:.4f} | {fa['not_found']}/{fa['n']} | [{fa['ci95'][0]:.4f}, {fa['ci95'][1]:.4f}] | target < 0.02; seed {fa['seed']} |",
        ]
    lines += [
        "",
        "## Per category",
        "",
        "| cat | description | pass | unsafe | n | note |",
        "|---|---|---|---|---|---|",
    ]
    desc = {
        "A": "Quran verbatim (+cross-ayah)",
        "B": "Quran orthographic fold",
        "C": "Quran near-miss",
        "D": "Quran-attributed prose not in corpus",
        "E": "Hadith verbatim",
        "F": "Hadith 1-token variant",
        "G": "Hadith heavy edits",
        "H": "Hadith-attributed prose not in corpus",
        "I": "Claimed source mismatch",
        "J": "Prompt injection",
        "K": "Non-Arabic / short",
        "L": "Out-of-scope requests",
        "M": "Offset robustness",
    }
    for cat in sorted(per_cat):
        a = per_cat[cat].summary()
        lines.append(
            f"| {cat} | {desc.get(cat, '')} | {a['pass']['k']}/{a['pass']['n']} | {a['unsafe']['k']} | {a['pass']['n']} | {'indicative (n<30)' if a['pass'].get('indicative') else ''} |"
        )
    fails = [d for d in details if not d["passed"]]
    lines += ["", f"## Failures ({len(fails)})", ""]
    if not fails:
        lines.append("none")
    for d in fails:
        lines.append(
            f"- **{d['id']}** got `{d['got']}` expected `{d['expected']}` — {'; '.join(d['reasons'])} ({'; '.join(d['notes'])})"
        )
    lines += [
        "",
        "## Limits of significance (read before quoting any number)",
        "",
        "- Cases are generated from corpus records by ID with mechanical mutations (`eval/gen_cases.py`, seed 20261004); they measure the **matching engine**, not real-world post distribution.",
        "- Categories have n < 30 → per-category rates are *indicative*; only the overall rates carry a CI.",
        "- The false-alarm set is verbatim corpus segments in neutral wrappers: it measures *recall of verbatim text*, not precision on real misquotes.",
        "- Mock provider: extraction variance is 0 by construction; with a real LLM provider re-run with `--repeats 3` and report the variance line.",
        "- Thresholds (0.75/0.70/0.60) are the initial values from ADR-002; this report is the calibration evidence, not an independent test of it.",
    ]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


async def main_async(args: argparse.Namespace) -> int:
    index = REPO / args.index
    store = load_store(index)
    retriever = Retriever(store)
    settings = Settings()
    cfg = Settings(index_dir=index, llm_provider=settings.llm_provider)
    manifest = json.loads(cfg.manifest_path.read_text(encoding="utf-8"))
    pipeline = Pipeline(
        store, retriever, make_llm(cfg.llm_provider), cfg, CorpusMeta.from_manifest(manifest, store.meta)
    )
    cases = yaml.safe_load(CASES.read_text(encoding="utf-8"))
    if args.category:
        cases = [c for c in cases if c["category"] in args.category]
    t0 = time.time()
    outcomes, details, variance = await run_cases(pipeline, cases, args.repeats)
    agg_all = Aggregate()
    per_cat: dict[str, Aggregate] = defaultdict(Aggregate)
    for o in outcomes:
        agg_all.add(o)
        per_cat[o.category].add(o)
    fa = None
    if args.false_alarm:
        fa = await run_false_alarm(pipeline, n=args.false_alarm, seed=20261004)
    meta = {
        "index": str(index.relative_to(REPO)),
        "records_sha256": store.meta.get("records_sha256", ""),
        "provider": pipeline.llm.name,
        "repeats": args.repeats,
        "date": time.strftime("%Y-%m-%d %H:%M UTC", time.gmtime()),
        "variance_cases": variance,
        "seconds": round(time.time() - t0, 1),
    }
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "latest.json").write_text(
        json.dumps(
            {
                "meta": meta,
                "summary": agg_all.summary(),
                "per_category": {k: v.summary() for k, v in per_cat.items()},
                "false_alarm": fa,
                "cases": details,
            },
            ensure_ascii=False,
            indent=1,
        ),
        encoding="utf-8",
    )
    write_report(agg_all, per_cat, details, fa, meta)
    s = agg_all.summary()
    print(
        f"cases: pass {s['pass']['k']}/{s['pass']['n']} · unsafe {s['unsafe']['k']} · recall@found {s['recall_found']['rate']} · precision@found {s['precision_found']['rate']} · forbidden {s['forbidden_hits']} · variance {variance} · {meta['seconds']}s"
    )
    if fa:
        print(f"false-alarm: {fa['not_found']}/{fa['n']} = {fa['rate']:.4f}")
    for d in details:
        if not d["passed"]:
            print(f"  FAIL {d['id']}: got {d['got']} expected {d['expected']} — {'; '.join(d['reasons'])}")
    if args.fail_on_unsafe and (s["unsafe"]["k"] or s["forbidden_hits"]):
        return 1
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument(
        "--index", default="corpus/fixture", help="index dir relative to repo (corpus/fixture | corpus/index)"
    )
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--false-alarm", type=int, default=0, help="number of verbatim segments (e.g. 500)")
    ap.add_argument("--category", nargs="*", help="limit to categories")
    ap.add_argument("--fail-on-unsafe", action="store_true")
    return asyncio.run(main_async(ap.parse_args()))


if __name__ == "__main__":
    sys.exit(main())
