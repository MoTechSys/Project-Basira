export const SITE: Record<Lang, Record<Keys, string>> = { ar, en };
export type SiteKey = Keys;

export function t(lang: Lang, key: SiteKey, vars: Record<string, string | number> = {}): string {
  return SITE[lang][key].replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function numfmt(lang: Lang): Intl.NumberFormat {
  return new Intl.NumberFormat(lang === "ar" ? "ar-SA" : "en");
}
